#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_agent_files.py — 从唯一源头生成 .claude/agents/*.md(重建批 2, 2026-09-30)。

源头(内容层, 两引擎共用):
    prompts/agent/roles/zealot.md   + prompts/agent/debater.md   → .claude/agents/zealot.md
    prompts/agent/roles/reaper.md   + prompts/agent/debater.md   → .claude/agents/reaper.md
    prompts/agent/roles/executor.md + prompts/agent/roles/scout.md  → .claude/agents/scout.md
    prompts/agent/roles/executor.md + prompts/agent/roles/runner.md → .claude/agents/runner.md
frontmatter(name / description / tools / model)由本脚本写入, 是引擎(Claude Code)的配置, 不是内容。
Codex 引擎的 codex_loop.py 读同一批生成物注入 subagent, 所以内容只维护一份。

用法:
    python scripts/gen_agent_files.py            # 生成(覆盖)
    python scripts/gen_agent_files.py --check    # 只比对, 过期则 exit 1(测试用)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "prompts" / "agent"
OUT = ROOT / ".claude" / "agents"

# 引擎配置: 辩手只读不联网(结构中立, 外呼只能申报); 执行者才有 Bash / WebSearch / WebFetch。
AGENTS = {
    "zealot": {
        "description": "Zealot (the optimist debater). Each round receives the symbol, data file paths and the view of prior-round finals, and outputs one report-form speech as strict JSON. Isolated context, no search tool; outcalls can only be filed.",
        "tools": "Read, Glob",
        "model": "opus",
        "parts": [SRC / "roles" / "zealot.md", SRC / "debater.md"],
    },
    "reaper": {
        "description": "Reaper (the realist debater). Each round receives the symbol, data file paths and the view of prior-round finals, and outputs one report-form speech as strict JSON. Isolated context, no search tool; outcalls can only be filed.",
        "tools": "Read, Glob",
        "model": "opus",
        "parts": [SRC / "roles" / "reaper.md", SRC / "debater.md"],
    },
    "scout": {
        "description": "Scout (neutral evidence gatherer). One question, one Scout: takes one targeted evidence request (the question may carry the requester's lean), decomposes and answers it neutrally, and returns the evidence shape with a conclusion. No stance; does not take part in the debate.",
        "tools": "Read, Glob, Bash, WebSearch, WebFetch",
        "model": "sonnet",
        "parts": [SRC / "roles" / "executor.md", SRC / "roles" / "scout.md"],
    },
    "runner": {
        "description": "Runner (model-call executor). One model call, one Runner: takes one model-call filing (model number, topic, parameters), Reads the corresponding manual and executes it by the book, and returns the result in the model-call shape. No stance; does not take part in the debate.",
        "tools": "Read, Glob, Bash, WebSearch, WebFetch",
        "model": "sonnet",
        "parts": [SRC / "roles" / "executor.md", SRC / "roles" / "runner.md"],
    },
    "translator": {
        "description": "Translator (the last step of a debate or postcheck; cheapest model, one per language). Takes one staging file under data/i18n_staging/, fills `translations` for every id in place, writes the file back and replies with the path and the count. No stance, no search, no database.",
        "tools": "Read, Edit, Write",
        "model": "haiku",
        "parts": [SRC / "roles" / "translator.md"],
    },
}

HEADER_NOTE = ("<!-- Generated by scripts/gen_agent_files.py; do not edit directly. "
               "Edit the source files under prompts/agent/ and regenerate. -->")


def render(name: str) -> str:
    spec = AGENTS[name]
    body = "\n\n---\n\n".join(p.read_text(encoding="utf-8").strip() for p in spec["parts"])
    fm = (f"---\nname: {name}\ndescription: {spec['description']}\n"
          f"tools: {spec['tools']}\nmodel: {spec['model']}\n---\n")
    return f"{fm}\n{HEADER_NOTE}\n\n{body}\n"


def outdated() -> list[str]:
    stale = []
    for name in AGENTS:
        target = OUT / f"{name}.md"
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != render(name):
            stale.append(str(target.relative_to(ROOT)))
    return stale


def generate() -> list[str]:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for name in AGENTS:
        target = OUT / f"{name}.md"
        target.write_bytes(render(name).encode("utf-8"))   # 写 LF, 不经文本层换行转换
        written.append(str(target.relative_to(ROOT)))
    return written


def main() -> None:
    if "--check" in sys.argv[1:]:
        stale = outdated()
        if stale:
            print("agent 文件过期(源头已改, 需重新生成): " + ", ".join(stale))
            sys.exit(1)
        print("agent 文件与源头一致")
        return
    for path in generate():
        print(f"生成 {path}")


if __name__ == "__main__":
    main()
