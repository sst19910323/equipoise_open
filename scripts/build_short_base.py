#!/usr/bin/env python3
"""build_short_base.py — short-horizon state base rates for the opening anchors (config/short_base.yaml).

What happened over the next 5 sessions after a symbol's 5-day or 1-day move fell in a fixed bucket, pooled over every
symbol with five years of daily bars, in that symbol's own daily-sigma units (sigma = SD of daily returns over the
trailing 250 sessions). Thresholds are fixed here, not fitted. Each row carries the two halves of the sample so the
reader sees how stable it is. `--cutoff` drops every observation whose 5-session outcome ends after that date, so a
table built for a frozen-material drill holds nothing later than the drill's nodes.

    ./venv/bin/python scripts/build_short_base.py --cutoff 2026-06-30
"""
from __future__ import annotations

import argparse
import csv
import glob
import math
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FWD, LOOK, STRIDE = 5, 250, 3
BUCKETS_5D = [("5d_down_2", "5-day fall of 2σ or more", None, -2.0), ("5d_down_1", "5-day fall of 1–2σ", -2.0, -1.0),
              ("5d_flat", "5-day move inside ±1σ", -1.0, 1.0), ("5d_up_1", "5-day rise of 1–2σ", 1.0, 2.0),
              ("5d_up_2", "5-day rise of 2σ or more", 2.0, None)]
BUCKETS_1D = [("1d_down_2", "1-day fall of 2σ or more", None, -2.0), ("1d_up_2", "1-day rise of 2σ or more", 2.0, None)]


def bucket(x: float, table: list) -> tuple | None:
    for key, label, lo, hi in table:
        if (lo is None or x > lo) and (hi is None or x <= hi) if hi is not None and hi <= 0 else \
           (lo is None or x >= lo) and (hi is None or x < hi):
            return key, label
    return None


def moves(closes: list[float], i: int) -> tuple[float, float, float] | None:
    """(5-day move, 1-day move, daily sigma) at index i, the moves in daily-sigma units (5-day ÷ √5)."""
    if i < LOOK + 1:
        return None
    r = [closes[k] / closes[k - 1] - 1 for k in range(i - LOOK + 1, i + 1)]
    sd = st.pstdev(r)
    if sd <= 0:
        return None
    return (closes[i] / closes[i - 5] - 1) / (sd * math.sqrt(5)), r[-1] / sd, sd


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cutoff", required=True, help="YYYY-MM-DD: last date an outcome may end on")
    ap.add_argument("--out", default=str(ROOT / "config" / "short_base.yaml"))
    a = ap.parse_args()
    obs, nsym = [], 0
    for d in sorted(glob.glob(str(ROOT / "data" / "market_data" / "*"))):
        files = sorted(glob.glob(f"{d}/*_5y_1d_*.csv"))
        if not files:
            continue
        with open(files[-1], newline="", encoding="utf-8") as fh:
            rows = [(r["date"][:10], float(r["close"])) for r in csv.DictReader(fh)]
        rows = [r for r in rows if r[0] <= a.cutoff]
        if len(rows) < LOOK + 300 or min(c for _, c in rows) <= 0:
            continue
        nsym += 1
        c = [x for _, x in rows]
        for i in range(LOOK + 1, len(c) - FWD, STRIDE):
            m = moves(c, i)
            if m:
                obs.append((rows[i][0], m[0], m[1], (c[i + FWD] / c[i] - 1) / (m[2] * math.sqrt(FWD))))
    obs.sort()
    half = obs[len(obs) // 2][0]

    def row(sel: list) -> dict:
        a_, b_ = [o for o in sel if o[0] < half], [o for o in sel if o[0] >= half]
        up = lambda g: round(sum(o[3] > 0 for o in g) / len(g), 3) if g else None  # noqa: E731
        return {"n": len(sel), "up": up(sel), "mean_sigma": round(st.mean(o[3] for o in sel), 3),
                "up_first_half": up(a_), "up_second_half": up(b_), "n_first_half": len(a_), "n_second_half": len(b_)}
    states = {"all": dict(row(obs), label="all days")}
    for key, label, *_ in BUCKETS_5D:
        states[key] = dict(row([o for o in obs if (bucket(o[1], BUCKETS_5D) or ("",))[0] == key]), label=label)
    for key, label, *_ in BUCKETS_1D:
        states[key] = dict(row([o for o in obs if (bucket(o[2], BUCKETS_1D) or ("",))[0] == key]), label=label)
    import yaml
    doc = {"cutoff": a.cutoff, "symbols": nsym, "observations": len(obs), "first": obs[0][0], "half_split": half,
           "forward_sessions": FWD, "stride": STRIDE,
           "unit": "moves and outcomes in the symbol's daily sigma (SD of daily returns, trailing 250 sessions); k-day ÷ √k",
           "states": states}
    Path(a.out).write_text("# generated by scripts/build_short_base.py — do not edit by hand\n"
                           + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True), encoding="utf-8")
    for k, v in states.items():
        print(f"{k:10s} n {v['n']:6d} up {v['up']} (halves {v['up_first_half']} / {v['up_second_half']}) mean {v['mean_sigma']:+.3f}σ")


if __name__ == "__main__":
    main()
